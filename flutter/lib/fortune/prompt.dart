/// 同一支签分给不同的人时，给模型一个专属切口，避免所有人读到同一段话。
/// 9 个切口按「账号 + 日期 + 签位」稳定取一个：同一个人当天重开看到的一样，
/// 换个人或换一天就换一个。
const List<String> kFortuneAngles = [
  '手上正在做的那件事',
  '注意力和专注',
  '说话的节奏、说什么不说什么',
  '身体的信号：睡、吃、坐太久',
  '桌上的物件和房间的样子',
  '时间和安排：先做哪件、拖哪件',
  '和人的来往：家人、同事、朋友',
  '钱和账目',
  '情绪的来处，不是情绪本身',
];

/// 稳定的 FNV-1a，用来把「人 + 天 + 签」摊到切口上。
int _stableHash(String s) {
  var h = 0x811c9dc5;
  for (final u in s.codeUnits) {
    h ^= u;
    h = (h * 0x01000193) & 0x7fffffff;
  }
  return h;
}

String fortuneAngleFor({
  required String owner,
  required DateTime day,
  required int idx,
}) {
  final key = '$owner|${day.year}-${day.month}-${day.day}|$idx';
  return kFortuneAngles[_stableHash(key) % kFortuneAngles.length];
}

/// 把当天上下文拼成用户消息。字段用清单式，避免模型把无关信息编成故事。
String buildFortunePrompt({
  required DateTime day,
  required String weekday,
  required int streak,
  required String level,
  required String kindLabel,
  required String baseName,
  required String baseDesc,
  required String baseYi,
  required String baseJi,
  String? lunar,
  String? festival,
  String? term,
  String? cardLabel,
  String? angle,
}) {
  final lines = <String>[
    '日期：${day.year} 年 ${day.month} 月 ${day.day} 日，$weekday',
    if (lunar != null && lunar.isNotEmpty) '农历：$lunar',
    if (festival != null && festival.isNotEmpty) '节日：$festival',
    if (term != null && term.isNotEmpty) '节气：$term',
    '连续打卡：$streak 天',
    '今天抽到的签：$level · $kindLabel',
    '原有签题：$baseName',
    '原有签文：$baseDesc',
    '原有宜：$baseYi；原有忌：$baseJi',
    if (cardLabel != null && cardLabel.isNotEmpty) '今天翻开的卡面类别：$cardLabel',
    if (angle != null && angle.isNotEmpty) '今天这个人要从这个切口读：$angle',
    '',
    '请按系统要求写这一支签的今日解。原有签题与签文只作基调参考，可以另起一个更贴今天的签题，但等级和签类不要改。'
        '「do」那一句请落到今天十分钟内真能做完的一件具体事上，写清楚对象和数量。'
        '这支签今天也会发给别人，请只从上面那个切口读，不要写成「谁都能用」的一段通用签文。',
  ];
  return lines.join(String.fromCharCode(10));
}
