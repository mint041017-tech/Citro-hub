/// 趣签总数，面板入口上直接写出来。
int get kFunSignCount => kFunSigns.length;

/// 每天打开签筒时先给一支固定的，摇之前不会每次都不一样。
FunSign funSignOfDay(DateTime day, {int salt = 0}) {
  final serial = DateTime.utc(
    day.year,
    day.month,
    day.day,
  ).difference(DateTime.utc(2020, 1, 1)).inDays;
  final slot = (serial + salt) % kFunSigns.length;
  return kFunSigns[slot < 0 ? slot + kFunSigns.length : slot];
}

/// 随机摇一支，尽量避开刚刚看过的那支。
FunSign randomFunSign({String? avoidId, math.Random? rng}) {
  if (kFunSigns.length < 2) return kFunSigns.first;
  final random = rng ?? math.Random();
  var sign = kFunSigns[random.nextInt(kFunSigns.length)];
  for (var k = 0; k < 6 && sign.id == avoidId; k++) {
    sign = kFunSigns[random.nextInt(kFunSigns.length)];
  }
  return sign;
}

/// 按签种取该组全部签，签筒里做「这一种还有几支」时用。
List<FunSign> funSignsOf(String kind) =>
    kFunSigns.where((s) => s.kind == kind).toList();
