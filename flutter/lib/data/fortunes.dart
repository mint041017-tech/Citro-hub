final int kFortunePoolSize = kSignPools.fold(0, (s, p) => s + p.length);

/// 以 2020-01-01 为原点的天数序号：连续日期必然 +1。
int _daySerial(DateTime day) => DateTime.utc(
  day.year,
  day.month,
  day.day,
).difference(DateTime.utc(2020, 1, 1)).inDays;

/// 稳定的 FNV-1a：没有服务端 slot 时，用它把日期散成一个不轮换的位置。
int _fortuneHash(String s) {
  var h = 0x811c9dc5;
  for (final u in s.codeUnits) {
    h ^= u;
    h = (h * 0x01000193) & 0x7fffffff;
  }
  return h;
}

/// 取当天这支签：等级由抽签决定，具体签也随机落在**同级六支**之一。
///
/// 同一天反复打开看到的是同一支；换一天重新随机，不再按日期逐日轮换。
/// [slot] 是服务端当天抽好的具体签位置（0..5），传了就按它取；
/// 没有 slot（旧缓存 / 离线兜底）时用日期 + 等级 + 账号散列一个稳定位置，
/// 仍然保持同一天不变，但不会形成可预测的轮换序列。
/// [salt] 保留给转运后的本地兜底，避免旧调用方拿不到 slot 时撞回同一支。
Fortune fortuneForDay(
  int lvIdx,
  DateTime day, {
  int salt = 0,
  int? slot,
  String owner = '',
}) {
  final lvi = lvIdx.clamp(0, kSignPools.length - 1);
  final pool = kSignPools[lvi];
  final picked = slot != null
      ? slot % pool.length
      : _fortuneHash('$owner|${_daySerial(day)}|$lvi|$salt') % pool.length;
  final pick = pool[picked];
  var ordinal = picked + 1;
  for (var i = 0; i < lvi; i++) {
    ordinal += kSignPools[i].length;
  }
  final meta = kFortunes[lvi];
  return Fortune(
    lv: meta.lv,
    name: pick.name,
    desc: pick.desc,
    yi: pick.yi,
    ji: pick.ji,
    color: meta.color,
    num: meta.num,
    poem: pick.poem,
    kind: pick.kind,
    step: pick.step,
    signIndex: ordinal,
    signId: pick.id,
    idx: lvi,
  );
}
