// 今日打卡 · FORTUNES[] 与 FESTIVAL_FORTUNES。
class Fortune {
  final String lv, name, desc, yi, ji;
  final int color;
  final List<int> num;
  final List<String> poem;
  final String? festival;
  final int? idx;

  /// 签类（见 [kFortuneKinds]）。节日签与旧签池为空。
  final String? kind;

  /// 签池自带的「今日一小步」文案储备。
  ///
  /// 签面已经不用它了——那一行只显示签房先生（AI）写出来的具体动作，
  /// 没写好就占位；这里保留作内容储备与离线内容审校用。
  final String? step;

  /// 在全部签池里的序号（1 起），用于「第 N / 48 签」。
  final int signIndex;

  /// 签的稳定 ID（例如 `ss-03`），打卡记录跨版本保存用。
  final String? signId;

  const Fortune({
    required this.lv,
    required this.name,
    required this.desc,
    required this.yi,
    required this.ji,
    required this.color,
    required this.num,
    required this.poem,
    this.festival,
    this.idx,
    this.kind,
    this.step,
    this.signIndex = 0,
    this.signId,
  });
}

